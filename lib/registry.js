function getEndpoint(id) {
  return endpointMap.get(id) || null;
}

/** 用示例参数构建一个可直接调用的 URL（用于健康检查与前端展示）。 */
function buildExampleQuery(endpoint, overrides = {}) {
  const used = new Set();
  const encode = (value) =>
    endpoint.rawPath ? String(value).replace(/\s/g, '%20') : encodeURIComponent(value);
  let path = endpoint.upstream;
  for (const p of endpoint.params || []) {
    const value = overrides[p.key] ?? p.example;
    if (value === undefined || value === null || value === '') continue;
    if (path.includes(`{${p.key}}`)) {
      path = path.split(`{${p.key}}`).join(encode(value));
      used.add(p.key);
    }
  }
  path = path.replace(/\{([^}]+)\}/g, (m, key) => {
    const p = (endpoint.params || []).find((x) => x.key === key);
    return p && p.example ? encode(p.example) : '';
  });
  const url = new URL(path);
  for (const p of endpoint.params || []) {
    if (used.has(p.key)) continue;
    const value = overrides[p.key] ?? p.example;
    if (value === undefined || value === null || value === '') continue;
    url.searchParams.set(p.key, value);
  }
  return url.toString();
}

function examplePath(endpoint) {
  const used = new Set();
  let qs = '';
  const queryParams = [];
  let path = endpoint.upstream;
  for (const p of endpoint.params || []) {
    if (path.includes(`{${p.key}}`)) {
      path = path.split(`{${p.key}}`).join(encodeURIComponent(p.example || 'value'));
      used.add(p.key);
    }
  }
  path = path.replace(/\{([^}]+)\}/g, (_, key) => {
    const p = (endpoint.params || []).find((x) => x.key === key);
    return encodeURIComponent((p && p.example) || 'value');
  });
  for (const p of endpoint.params || []) {
    if (used.has(p.key) || p.example === '') continue;
    queryParams.push(`${encodeURIComponent(p.key)}=${encodeURIComponent(p.example)}`);
  }
  if (queryParams.length) qs = `?${queryParams.join('&')}`;
  return `/api/r/${endpoint.id}${qs}`;
}

function publicCatalog() {
  return {
    name: 'API Router',
    version: '1.0.0',
    updatedAt: '2026-11-15',
    categories,
    total: endpoints.length,
    endpoints: endpoints.map((e) => ({
      id: e.id,
      name: e.name,
      category: e.category,
      icon: e.icon,
      desc: e.desc,
      path: `/api/r/${e.id}`,
      example: examplePath(e),
      tags: e.tags || [],
      params: e.params || [],
      ttl: e.ttl || 0,
      note: e.note || '',
      docs: e.docs || '',
      kind: e.kind || 'proxy',
      binary: e.category === 'image',
      process: e.process || '',
    })),
    categoriesMeta: categories.map((c) => ({
      ...c,
      count: endpoints.filter((e) => e.category === c.id).length,
    })),
  };
}

